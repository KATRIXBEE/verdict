export function lookupIPC(sectionStr: string): IPCDictionaryEntry {
  const clean = sectionStr.trim();
  if (IPC_DICTIONARY[clean]) {
    return IPC_DICTIONARY[clean];
  }
  
  // Fuzzy match (e.g. "420" -> "IPC 420")
  for (const key of Object.keys(IPC_DICTIONARY)) {
    if (key.toLowerCase().includes(clean.toLowerCase()) || clean.toLowerCase().includes(key.toLowerCase())) {
      return IPC_DICTIONARY[key];
    }
  }

  return {
    section: sectionStr,
    title: `Section ${sectionStr}`,
    plainEnglish: "Statutory penal charge under Indian law. Sourced directly from filed Form 26 affidavit.",
    severityTier: "moderate",
    deductionPoints: 1.5,
    maxSentence: "Under judicial scrutiny",
    bailable: true,
    category: "General Offense",
  };
}
