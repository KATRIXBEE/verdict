export function getAllIndiaRankings(): (RankingIndex & { categoryKey: string; categoryLabel: string })[] {
  const result: (RankingIndex & { categoryKey: string; categoryLabel: string })[] = [];
  for (const [catKey, group] of Object.entries(INDIA_RANKINGS_DATA)) {
    for (const item of group.indices) {
      result.push({
        ...item,
        categoryKey: catKey,
        categoryLabel: group.label,
      });
    }
  }
  return result;
}
